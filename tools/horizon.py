#!/usr/bin/env python3
"""Export pinned sources, apply the template bundle and build a native Horizon."""
import argparse
import contextlib
import fcntl
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import tempfile
import time

ROOT = Path(__file__).resolve().parents[1]
COMPAT = json.loads((ROOT / "compatibility.json").read_text())
PIN = COMPAT["horizon_revision"]
# Defaults point at the campaign's read-only pin checkouts, never at the stale
# campaign `horizon/` tree. Override with HORIZON_MIXINS / --horizon.
MIXINS = Path(os.environ.get("HORIZON_MIXINS", ROOT.parent / "_shared/pins/horizon-mixins-5a64af9")).resolve()
DEFAULT_HORIZON = ROOT.parent / "_shared/pins/horizon-1d63e0a"
# Shared-cache overrides (ports/tools/build-slot.sh sets these per slot):
# a stable staged path makes cargo reuse every unmodified pin crate across
# ports, because a path dependency's package id includes its path.
STAGES = Path(os.environ.get("HORIZON_STAGE_ROOT", ROOT / "target/mixins"))
DEFAULT_TARGET = Path(os.environ.get("HORIZON_TARGET_DIR", ROOT / "target/horizon-cargo"))

# The launcher's generated executable installs the bundle as a trait mod; the source-mixin path
# does not. `mod_api::mods()` must be non-empty for the pin's `spawn_hooks()` gate, so the
# harness's `main` installs one empty trait mod (the bundle's HEAD helpers are already injected).
HARNESS_MAIN = '''//! Generated by the torchmaster harness (mirrors the launcher's main).
#![forbid(unsafe_code)]

#[global_allocator]
static ALLOCATOR: horizon_threads::Allocator = horizon_threads::ALLOCATOR;

static MOD_API_LEVEL: [u8; horizon_mods::api_level::MARK.len()] = horizon_mods::api_level::MARK;

/// The launcher installs the bundle's own `Hooks`; this stand-in only makes `mods()` non-empty.
struct TorchmasterHarness;
impl horizon_client::mod_api::Hooks for TorchmasterHarness {}

fn main() {
    std::hint::black_box(&MOD_API_LEVEL);
    let mods: horizon_client::mod_api::Mods =
        vec![Box::new(TorchmasterHarness) as Box<dyn horizon_client::mod_api::Hooks>].into();
    horizon_client::entry::main_with(mods);
}
'''


def digest(data):
    return hashlib.sha256(data).hexdigest()


def stage(horizon, stages):
    if not (horizon / ".git").exists():
        raise ValueError("--horizon must be a Git checkout (including a worktree)")
    subprocess.run(["git", "-C", str(horizon), "cat-file", "-e", PIN + "^{commit}"], check=True, capture_output=True)
    inputs = {"revision": PIN.encode(), "export-schema": b"2"}
    signature = digest(b"".join(k.encode() + b"\0" + value for k, value in sorted(inputs.items())))
    stages.mkdir(parents=True, exist_ok=True)
    out = stages / signature[:20]
    if out.exists():
        marker = json.loads((out / ".horizon-mod-template.json").read_text())
        if marker["signature"] != signature:
            raise ValueError(f"stage marker mismatch: {out}")
        for path, expected in marker["files"].items():
            if digest((out / path).read_bytes()) != expected:
                raise ValueError(f"staged source was edited: {path}; remove this generated stage to rebuild it")
        return out, False
    temporary = Path(tempfile.mkdtemp(prefix=".mod-template-stage-", dir=stages))
    try:
        process = subprocess.Popen(["git", "-C", str(horizon), "archive", "--format=tar", PIN], stdout=subprocess.PIPE)
        try:
            with tarfile.open(fileobj=process.stdout, mode="r|") as archive:
                for member in archive:
                    archive.extract(member, temporary, filter="data")
        finally:
            process.stdout.close()
            code = process.wait()
        if code:
            raise ValueError(f"git archive exited {code}")
        for path, expected in COMPAT["source_sha256"].items():
            if digest((temporary / path).read_bytes()) != expected:
                raise ValueError(f"pinned source hash mismatch: {path}")
        # Materialize the committed documentation symlink for the mixin CLI's
        # symlink-free source snapshot. No Rust source is edited here.
        for file in temporary.rglob("*"):
            if file.is_symlink():
                content = file.read_bytes()
                file.unlink()
                file.write_bytes(content)
        (temporary / ".horizon-revision").write_text(PIN + "\n")
        # The source tree itself is deterministic. Cargo outputs live elsewhere.
        files = {str(p.relative_to(temporary)): digest(p.read_bytes())
                 for p in sorted(temporary.rglob("*")) if p.is_file()}
        (temporary / ".horizon-mod-template.json").write_text(json.dumps(
            {"signature": signature, "horizon_revision": PIN, "files": files}, sort_keys=True, indent=2) + "\n")
        os.rename(temporary, out)
    except BaseException:
        shutil.rmtree(temporary, ignore_errors=True)
        raise
    return out, True


def mixin_stage(horizon, stages):
    revision = subprocess.check_output(["git", "-C", str(MIXINS), "rev-parse", "HEAD"], text=True).strip()
    if revision != COMPAT["horizon_mixins_revision"]:
        raise ValueError(f"horizon-mixins must be pinned at {COMPAT['horizon_mixins_revision']}, got {revision}")
    subprocess.run(["git", "-C", str(MIXINS), "diff", "--quiet", "HEAD", "--", "Cargo.toml", "Cargo.lock", "crates"], check=True)
    original, _ = stage(horizon, stages / "original")
    subprocess.run(["cargo", "build", "--locked", "--offline", "--target-dir", str(MIXINS / "target"), "-p", "horizon-mixins-cli"], cwd=MIXINS, check=True, stdout=sys.stderr)
    cli = MIXINS / "target/debug/horizon-mixins"
    output = stages / "modded"
    plan = stages / "plan.json"
    # The launcher reads `[api]` (the trait-mod shim) but horizon-mixins 5a64af9's manifest
    # parser does not; stage a copy without it. The shipped manifest keeps it for the launcher.
    harness = stages / "harness-mods"
    if harness.exists():
        shutil.rmtree(harness)
    shutil.copytree(ROOT / "mixins", harness)
    for manifest in harness.glob("*/horizon-mixin.toml"):
        kept, skip = [], False
        for line in manifest.read_text().splitlines():
            if line.strip() == "[api]":
                skip = True
                continue
            if skip and line.strip().startswith("["):
                skip = False
            if not skip:
                kept.append(line)
        manifest.write_text("\n".join(kept) + "\n")
    base = ["--workspace", str(original), "--mods", str(harness)]
    subprocess.run([str(cli), "plan", *base, "--out", str(plan)], check=True, capture_output=True, text=True)
    applied = subprocess.run([str(cli), "apply", *base, "--out", str(output)], check=True, capture_output=True, text=True)
    report = json.loads(applied.stdout)
    # The launcher installs a bundle as a trait mod (`main_with(mods)`), which is what makes
    # `mod_api::mods()` non-empty. The source-mixin path injects HEAD helpers but leaves the
    # stock `main` with `Default::default()`, and the pin's `NaturalLevel::spawn_hooks`
    # (`natural_spawning.rs:450`) then skips `potential_spawns` entirely. Mirror the launcher
    # for the harness: one empty trait mod, so the injected helper is reached. The shipped
    # `.hnmod` is compiled by the launcher and installs the bundle's own `Hooks`.
    (output / "crates/horizon-client/src/main.rs").write_text(HARNESS_MAIN)
    report["harness_main"] = "torchmaster"
    return output, report["stage_changed"]


@contextlib.contextmanager
def lock(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a") as handle:
        fcntl.flock(handle, fcntl.LOCK_EX)
        yield


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["stage", "check", "build", "test", "ctl"])
    parser.add_argument("--horizon", type=Path, default=DEFAULT_HORIZON)
    parser.add_argument("--target-dir", type=Path, default=DEFAULT_TARGET)
    args = parser.parse_args()
    horizon = args.horizon.resolve()
    target = args.target_dir.resolve()
    if target.is_relative_to(horizon):
        parser.error("Cargo target must be outside the original Horizon checkout")
    started = time.monotonic()
    with lock(ROOT / "target/stage.lock"):
        output, changed = mixin_stage(horizon, STAGES)
        if target.is_relative_to(output) or output.is_relative_to(target):
            parser.error("Cargo target and generated source stage must be separate")
        report = {"stage": str(output), "stage_changed": changed,
                  "horizon_revision": PIN, "staging_seconds": time.monotonic()-started}
        if args.action != "stage":
            if args.action == "ctl":
                # horizon-ctl lives in the library package at the pin; e2e.sh
                # expects it at target/fast/horizon-ctl beside the game binary.
                command = ["cargo", "build", "--locked", "--offline", "-p", "horizon-client-lib",
                           "--bin", "horizon-ctl", "--no-default-features",
                           "--target-dir", str(target), "--profile", "fast"]
            else:
                command = ["cargo", args.action, "--locked", "--offline", "-p", "horizon-client",
                           "--no-default-features", "--target-dir", str(target)]
                if args.action == "build":
                    command.extend(["--bin", "horizon-client", "--profile", "fast"])
                if args.action == "test":
                    # The embedded tests live in the lib since the 83ad384f pin; the
                    # old `--bin horizon-client` form runs 0 tests vacuously.
                    command.extend(["--lib", "game::torchmaster::tests", "--", "--nocapture"])
            with lock(target.parent / (target.name + ".mod-template.lock")):
                run_start = time.monotonic()
                result = subprocess.run(command, cwd=output, capture_output=True, text=True)
            report.update(cargo_seconds=time.monotonic()-run_start, cargo_command=command,
                          cargo_exit=result.returncode)
            log = ROOT / "target" / f"horizon-{args.action}.log"
            log.write_text(result.stdout + result.stderr)
            report["cargo_log"] = str(log)
            if result.returncode:
                print(result.stderr[-12000:], file=sys.stderr)
                print(json.dumps(report), file=sys.stderr)
                return result.returncode
            if args.action in ("build", "ctl"):
                report["binary"] = str(target / ("fast/horizon-client" if args.action == "build" else "fast/horizon-ctl"))
        print(json.dumps(report, indent=2))
        return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        if isinstance(error, subprocess.CalledProcessError) and error.stderr:
            print(error.stderr, file=sys.stderr)
        print(f"Native mod: {error}", file=sys.stderr)
        raise SystemExit(1)
